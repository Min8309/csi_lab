from pathlib import Path
import pandas as pd

# =========================================================
# 경로
# =========================================================

BASE_DIR = Path(__file__).resolve().parent.parent
PROCESSED_DIR = BASE_DIR / "processed"

INPUT = PROCESSED_DIR / "crime_analysis_grouped_1990_2022.csv"
OUTPUT = PROCESSED_DIR / "crime_analysis_refined_1990_2022.csv"

df = pd.read_csv(INPUT, encoding="utf-8-sig")


# =========================================================
# 1. 상위 집계 항목 판별
# =========================================================

AGGREGATE_NAMES = {
    "총계",
    "총범죄",
    "형법범",
    "특별법범",
    "기타형법범",
    "기타특별법",
    "강력범",
    "폭력범",
    "지능범",
    "풍속범",
    "교통사범",
}


def is_aggregate(name):
    name = str(name).strip()
    return name in AGGREGATE_NAMES


df["is_aggregate"] = (
    df["crime_type_original"]
    .apply(is_aggregate)
)


# =========================================================
# 2. CSI LAB 분석용 범죄군 보정
# =========================================================

def classify_refined(name):

    n = str(name).replace(" ", "")

    # -----------------------------------------------------
    # 살인
    # -----------------------------------------------------

    if any(x in n for x in [
        "살인",
        "영아살해",
        "존속살해",
        "자살교사",
        "자살방조"
    ]):
        return "살인"

    # -----------------------------------------------------
    # 강도
    # -----------------------------------------------------

    if "강도" in n:
        return "강도"

    # -----------------------------------------------------
    # 성범죄
    # -----------------------------------------------------

    if any(x in n for x in [
        "강간",
        "강제추행",
        "유사강간",
        "성폭력",
        "성매매",
        "간음",
        "추행",
        "윤락"
    ]):
        return "성범죄"

    # -----------------------------------------------------
    # 절도
    # -----------------------------------------------------

    if any(x in n for x in [
        "절도",
        "도둑",
        "장물"
    ]):
        return "절도"

    # -----------------------------------------------------
    # 폭력
    # -----------------------------------------------------

    if any(x in n for x in [
        "폭행",
        "상해",
        "폭력",
        "협박",
        "공갈"
    ]):
        return "폭력"

    # -----------------------------------------------------
    # 재산·경제
    # -----------------------------------------------------

    if any(x in n for x in [
        "사기",
        "횡령",
        "배임",
        "부정수표",
        "여신전문금융",
        "부당이득"
    ]):
        return "재산·경제"

    # -----------------------------------------------------
    # 손괴
    # -----------------------------------------------------

    if any(x in n for x in [
        "손괴",
        "재물손괴"
    ]):
        return "손괴"

    # -----------------------------------------------------
    # 위조
    # -----------------------------------------------------

    if any(x in n for x in [
        "위조",
        "변조",
        "통화위조"
    ]):
        return "위조"

    # -----------------------------------------------------
    # 방화
    # -----------------------------------------------------

    if any(x in n for x in [
        "방화",
        "실화"
    ]):
        return "방화"

    # -----------------------------------------------------
    # 마약
    # -----------------------------------------------------

    if any(x in n for x in [
        "마약",
        "대마",
        "향정"
    ]):
        return "마약"

    # -----------------------------------------------------
    # 도박
    # -----------------------------------------------------

    if "도박" in n:
        return "도박"

    # -----------------------------------------------------
    # 공직·부패
    # -----------------------------------------------------

    if any(x in n for x in [
        "뇌물",
        "알선수재",
        "수재",
        "직무유기",
        "공무상비밀누설"
    ]):
        return "공직·부패"

    # -----------------------------------------------------
    # 지식재산
    # -----------------------------------------------------

    if any(x in n for x in [
        "저작권",
        "상표법",
        "특허법",
        "실용신안"
    ]):
        return "지식재산"

    # -----------------------------------------------------
    # 교통
    # -----------------------------------------------------

    if any(x in n for x in [
        "도로교통",
        "교통사고",
        "도주차량",
        "자동차손해배상"
    ]):
        return "교통"

    # -----------------------------------------------------
    # 기타
    # -----------------------------------------------------

    return "기타"


df["crime_group_refined"] = (
    df["crime_type_original"]
    .apply(classify_refined)
)


# =========================================================
# 3. 복합범죄 관련 태그
# =========================================================

TAG_RULES = {
    "살인": [
        "살인", "살해"
    ],

    "강도": [
        "강도"
    ],

    "성범죄": [
        "강간", "추행", "간음",
        "성폭력", "성매매"
    ],

    "절도": [
        "절도", "장물"
    ],

    "폭력": [
        "폭행", "상해", "협박", "공갈"
    ],

    "사기": [
        "사기"
    ],

    "방화": [
        "방화", "실화"
    ],

    "마약": [
        "마약", "대마", "향정"
    ],

    "도박": [
        "도박"
    ],

    "위조": [
        "위조", "변조"
    ]
}


def make_related_groups(name):

    n = str(name).replace(" ", "")

    tags = []

    for group, keywords in TAG_RULES.items():

        if any(keyword in n for keyword in keywords):
            tags.append(group)

    if not tags:
        return ""

    return "|".join(tags)


df["related_groups"] = (
    df["crime_type_original"]
    .apply(make_related_groups)
)


df["is_multi_group"] = (
    df["related_groups"]
    .fillna("")
    .str.contains(r"\|")
)


# =========================================================
# 4. CSI LAB 활용 여부
# =========================================================

CSI_GROUPS = {
    "살인",
    "강도",
    "성범죄",
    "절도",
    "폭력",
    "재산·경제",
    "손괴",
    "위조",
    "방화",
    "마약",
    "도박",
    "공직·부패",
    "지식재산",
    "교통"
}


df["csi_analysis_group"] = (
    df["crime_group_refined"]
    .isin(CSI_GROUPS)
)


# 상위 집계행은 개별 범죄 합산에 사용하지 않음
df["include_detail_analysis"] = (
    ~df["is_aggregate"]
)


# =========================================================
# 5. 저장
# =========================================================

df.to_csv(
    OUTPUT,
    index=False,
    encoding="utf-8-sig"
)


